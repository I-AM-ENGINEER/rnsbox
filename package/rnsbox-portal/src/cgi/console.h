// console.h — the PTY broker behind the terminal tabs and its local clients.
//
// The portal itself is CGI: it cannot hold a terminal between requests. A tiny
// broker daemon (same binary, `rnsbox-portal console-broker`) owns one PTY per
// named session, keeps a bounded ring of each session's output, and serves
// attached stream clients plus one-shot input/resize commands over a root-only
// Unix socket. Sessions:
//   shell     — the operator's admin login shell (Console tab)
//   nomadnet  — NomadNet's TUI client (NomadNet tab); started on first attach
// The CGI routes authenticate against the portal session and bridge that socket
// to ordinary HTTP (chunked output + POSTed keystrokes), so the terminals stay
// on the portal's port 80 with no second listener.
#ifndef RNSBOX_CONSOLE_H
#define RNSBOX_CONSOLE_H

#include <string>

namespace console {

extern const char SOCK_PATH[];
extern const char PID_PATH[];

// Session names understood by attach/send_input/send_resize (and by the
// broker's handshake).
extern const char SESSION_SHELL[];
extern const char SESSION_NOMADNET[];

// Run the broker. Called for `rnsbox-portal console-broker [-f]`; returns 0
// when another broker is already alive, non-zero on setup failure. With -f it
// stays in the foreground (live debugging), otherwise it double-forks.
int broker_main(bool foreground);

// CGI side: connect to the broker. Returns a blocking fd or -1.
int connect_session();

// Attach this connection to `session`'s output stream (no reply, output
// follows). Starts the session if it is not running yet.
bool attach(int fd, const std::string& session, int cols, int rows);

// Feed raw bytes to `session`'s PTY (arbitrary control sequences, UTF-8,
// NUL-free).
bool send_input(int fd, const std::string& session, const std::string& data);

// Resize `session`'s PTY (SIGWINCH is generated by the kernel for the
// foreground pgrp).
bool send_resize(int fd, const std::string& session, int cols, int rows);

}  // namespace console
#endif
