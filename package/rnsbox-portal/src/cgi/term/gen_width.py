#!/usr/bin/env python3
"""Generate width_tables.h from Python's Unicode database.

The terminal model needs three widths: 0 (combining / zero-width), 2 (East
Asian Wide/Fullwidth), 1 (everything else).  Keeping the table generated means
the build stays dependency-free and the ranges match the Unicode version the
host Python knows about.

Run from this directory:  python3 gen_width.py > width_tables.h
"""

import sys
import unicodedata

MAX = 0x110000


def ranges(pred):
    out = []
    start = None
    for cp in range(MAX):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAX - 1))
    return out


def is_zero(cp):
    # C0/C1 are handled by the parser, not the width table.
    if cp < 0x20 or 0x7F <= cp <= 0x9F:
        return False
    cat = unicodedata.category(chr(cp))
    if cat in ("Mn", "Me", "Cf"):
        return True
    # Hangul jamo medial/final are zero-width with the preceding leading jamo;
    # wcwidth treats them as zero.
    if 0x1160 <= cp <= 0x11FF:
        return True
    return False


def is_wide(cp):
    if cp < 0x1100:
        return False
    return unicodedata.east_asian_width(chr(cp)) in ("W", "F")


def emit(name, rs):
    print(f"static const Range {name}[] = {{")
    line = "    "
    for lo, hi in rs:
        item = "{0x%X,0x%X}," % (lo, hi)
        if len(line) + len(item) + 1 > 100:
            print(line)
            line = "    "
        line += item
    if line.strip():
        print(line)
    print("};")
    print(f"static const size_t {name}_count = sizeof({name}) / sizeof({name}[0]);")
    print()


def main():
    zero = ranges(is_zero)
    wide = ranges(is_wide)
    print("// Generated by gen_width.py from Python %s / Unicode %s. Do not edit."
          % (sys.version.split()[0], unicodedata.unidata_version))
    print("#ifndef RNSBOX_TERM_WIDTH_TABLES_H")
    print("#define RNSBOX_TERM_WIDTH_TABLES_H")
    print("#include <cstddef>")
    print("#include <cstdint>")
    print()
    print("namespace term {")
    print("struct Range { uint32_t lo, hi; };")
    print()
    emit("kZeroWidth", zero)
    emit("kWideWidth", wide)
    print("}  // namespace term")
    print("#endif")


if __name__ == "__main__":
    main()
